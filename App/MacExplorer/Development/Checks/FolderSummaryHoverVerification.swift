#if DEBUG
import AppKit
import Darwin
import ExplorerCore

/// Native file-view callback delivery, distinct from physical pointer delivery.
/// Reuses the ordinary target and a tiny generated two-file fixture. The scanner
/// reads metadata only; the check creates no alternate source/build graph.
@MainActor
enum FolderSummaryHoverVerification {
    static func runFocused() async {
        do {
            let arguments = ProcessInfo.processInfo.arguments
            guard let index = arguments.firstIndex(of: "--analysis-source"), index + 1 < arguments.count else {
                throw UIVerification.Failure(message: "The exact generated hover fixture is required")
            }
            let result = try await run(root: URL(fileURLWithPath: arguments[index + 1]))
            if let raw = ProcessInfo.processInfo.environment["MAC_EXPLORER_TEST_ROOT"] {
                try JSONSerialization.data(withJSONObject: result, options: [.prettyPrinted, .sortedKeys])
                    .write(to: URL(fileURLWithPath: raw).appendingPathComponent("evidence/native-hover-summary.json"), options: .withoutOverwriting)
            }
            print("MAC_EXPLORER_SUMMARY_HOVER " + String(decoding:
                try JSONSerialization.data(withJSONObject: result, options: [.sortedKeys]), as: UTF8.self))
            Darwin.exit(0)
        } catch {
            await ApplicationStorageAnalysis.shared.stopAndDrain()
            let message = (error as? UIVerification.Failure)?.message ?? "Generated hover verification failed"
            FileHandle.standardError.write(Data(("MAC_EXPLORER_HOVER_READABILITY_FAILED " + String(message.prefix(2_048)) + "\n").utf8))
            Darwin.exit(1)
        }
    }
    private static func wait(_ message: String, _ condition: () -> Bool) async throws {
        let deadline = ProcessInfo.processInfo.systemUptime + 5
        while !condition(), ProcessInfo.processInfo.systemUptime < deadline { try await Task.sleep(for: .milliseconds(10)) }
        try UIVerification.require(condition(), message)
    }
    static func run(root: URL) async throws -> [String: Any] {
        var repository = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
        for _ in 0..<3 { repository.deleteLastPathComponent() }
        guard let raw = ProcessInfo.processInfo.environment["MAC_EXPLORER_TEST_ROOT"] else {
            throw UIVerification.Failure(message: "Generated hover profile required")
        }
        let profile = URL(fileURLWithPath: raw)
        let marker = try JSONSerialization.jsonObject(with: Data(contentsOf: profile.appendingPathComponent("reservation.json"))) as? [String: Any]
        try UIVerification.require(profile.deletingLastPathComponent() == repository.appendingPathComponent(".build/traverse-development")
            && UUID(uuidString: profile.lastPathComponent)?.uuidString == profile.lastPathComponent
            && profile.resolvingSymlinksInPath() == profile && root == profile.appendingPathComponent("source")
            && root.resolvingSymlinksInPath() == root && marker?["action"] as? String == "hover-summary-readability",
            "Only the current generated summary fixture is admitted")
        let settings = BrowserSettings(persist: false)
        settings.autoRefreshFolders = false; settings.folderSummaryDelay = 0.3
        settings.restoresSession = false; settings.reviewsRecoveryAtStartup = false
        InterfacePresentation.shared.bind(settings)
        let browser = BrowserViewController(settings: settings)
        // This check sends one exact native callback and verifies its lifetime;
        // it does not move the physical pointer. A real exit/move generated by
        // the window appearing under that pointer would cancel the injected
        // dwell correctly, so isolate only those unrelated pointer callbacks.
        _ = browser.folderSummary
        let summaryPointer = browser.table.onSummaryPointer
        var deliveringGeneratedPointer = false
        browser.table.onSummaryPointer = { point in
            if deliveringGeneratedPointer { summaryPointer?(point) }
        }
        browser.pinsController = BrowserPinsController(stateDirectory: nil)
        browser.folderAccess = FolderAccessController(stateDirectory: nil)
        browser.privateNames = ApplicationPrivateNames(directory: profile.appendingPathComponent("state/names"), settings: settings)
        let analysis = ApplicationStorageAnalysis.shared
        analysis.enablePagedForQualification(storage: try .init(directory: profile.appendingPathComponent("cache/analysis")))
        let window = NSWindow(contentRect: .init(x: 180, y: 160, width: 1000, height: 680),
                              styleMask: [.titled, .closable], backing: .buffered, defer: false)
        window.isReleasedWhenClosed = false; window.contentViewController = browser; window.acceptsMouseMovedEvents = true
        let properties = FilePropertiesWindowController(retainAccess: { _ in FileAccessLifetimes(leases: []) }, copyPaths: { _ in })
        defer { browser.suspendBrowser(); browser.settingsWindow?.close(); properties.close(); window.close() }
        window.makeKeyAndOrderFront(nil); NSApplication.shared.activate()
        var began = false
        browser.didFinishBeginForVerification = { began = true }
        browser.begin()
        try await wait("Native browser startup did not finish") { began }
        // begin's reference task can finish before its asynchronous computer
        // listing. Navigating then would correctly retire that volume ticket.
        try await wait("Initial native volume discovery did not finish") { !browser.volumes.isEmpty && !browser.isLoading }
        browser.didFinishBeginForVerification = nil
        browser.navigate(to: .directory(root))
        try await wait("Generated hover listing unavailable") { !browser.isLoading && browser.orderingTask == nil }
        try await wait("Generated hover window did not become key") { window.isKeyWindow }
        window.contentView?.layoutSubtreeIfNeeded()
        guard let row = browser.displayedEntries.firstIndex(where: { $0.name == "steamapps" }) else {
            throw UIVerification.Failure(message: "Generated folder row unavailable")
        }
        var lastPoint = NSPoint.zero
        func hover() throws {
            window.contentView?.layoutSubtreeIfNeeded()
            let cell = browser.table.rect(ofRow: row)
            lastPoint = browser.table.convert(NSPoint(x: cell.minX + 50, y: cell.midY), to: nil)
            guard let moved = NSEvent.mouseEvent(with: .mouseMoved, location: lastPoint, modifierFlags: [],
                timestamp: ProcessInfo.processInfo.systemUptime, windowNumber: window.windowNumber,
                context: nil, eventNumber: 1, clickCount: 0, pressure: 0) else {
                throw UIVerification.Failure(message: "Native callback event unavailable")
            }
            deliveringGeneratedPointer = true
            defer { deliveringGeneratedPointer = false }
            browser.table.mouseMoved(with: moved)
        }
        func check() async throws {
            func ready() -> Bool {
                guard let text = browser.folderSummary.summaryTextsForVerification else { return false }
                return text.counts.contains("2 files") && text.size.contains("70 bytes")
            }
            let deadline = ProcessInfo.processInfo.systemUptime + 5
            while !ready(), ProcessInfo.processInfo.systemUptime < deadline { try await Task.sleep(for: .milliseconds(10)) }
            let point = browser.table.convert(lastPoint, from: nil)
            try UIVerification.require(ready(), "Actual native folder callback did not present a populated summary: "
                + browser.folderSummary.summaryStateForVerification
                + " · row \(browser.table.row(at: point)) · key \(window.isKeyWindow) · volumes \(browser.volumes.count) · retained \(browser.summaryBrowsingAccess != nil)"
                + " · checkpoint \(browser.folderSummary.checkpointForVerification?.checkpoint.rawValue ?? "none")"
                + " · flags \(browser.folderSummary.checkpointForVerification?.flags.map(\.rawValue).joined(separator: ",") ?? "none")")
        }
        let starts = analysis.allScanStartsForSessionReuseVerification
        try hover(); try await check()
        try await wait("First actual hover scan did not drain") { !analysis.hasWork }
        try UIVerification.require(analysis.allScanStartsForSessionReuseVerification == starts + 1,
            "First hover did not run the actual scanner")
        browser.folderSummary.cancel()
        try hover(); try await check()
        try await wait("Repeated hover did not settle") { !analysis.hasWork }
        try UIVerification.require(analysis.allScanStartsForSessionReuseVerification == starts + 1,
            "Repeated dwell unexpectedly rescanned a recent complete observation")
        properties.show(urls: [root.appendingPathComponent("steamapps")])
        try await wait("Retained Properties metadata unavailable") { !properties.model.isLoading }
        window.makeKeyAndOrderFront(nil)
        try await wait("Main browser did not regain key status") { window.isKeyWindow }
        try hover(); try await check()
        browser.showSettings(nil)
        try UIVerification.require(browser.settingsWindow?.isVisible == true && properties.window?.isVisible == true,
            "The retained Settings/Properties control was not exercised")
        window.makeKeyAndOrderFront(nil)
        try await wait("Main browser did not regain key status after Settings") { window.isKeyWindow }
        try hover(); try await check()
        browser.folderSummary.cancel()
        settings.folderSummariesEnabled = false
        await Task.yield(); try hover()
        try await Task.sleep(for: .milliseconds(350))
        try UIVerification.require(!browser.folderSummary.isVisible, "Disabled automatic summaries remained visible")
        settings.folderSummariesEnabled = true
        await Task.yield(); try hover(); try await check()
        var readability = false
        if ProcessInfo.processInfo.arguments.contains("--hover-readability") {
            var repository = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
            for _ in 0..<3 { repository.deleteLastPathComponent() }
            guard let raw = ProcessInfo.processInfo.environment["MAC_EXPLORER_TEST_ROOT"] else {
                throw UIVerification.Failure(message: "Generated hover output authority is missing")
            }
            let output = URL(fileURLWithPath: raw, isDirectory: true)
            try UIVerification.require(output.deletingLastPathComponent() == repository.appendingPathComponent(".build/traverse-development")
                && output.resolvingSymlinksInPath() == output
                && UUID(uuidString: output.lastPathComponent)?.uuidString == output.lastPathComponent,
                "Only the exact generated hover output case is admitted")
            let authority = try JSONSerialization.jsonObject(with: Data(contentsOf: output.appendingPathComponent("reservation.json"))) as? [String: Any]
            try UIVerification.require(authority?["action"] as? String == "hover-summary-readability",
                "Incorrect generated hover output authority")
            for percent in [100, 150] {
                browser.folderSummary.cancel()
                settings.interfaceSize = .init(percent)
                await Task.yield()
                try await wait("Native hover row metrics did not update") {
                    abs(browser.table.rowHeight - ceil(settings.rowDensity.rowHeight * CGFloat(percent) / 100)) < 0.1
                }
                try hover(); try await check()
                guard let presentation = browser.folderSummary.summaryPresentationForVerification else {
                    throw UIVerification.Failure(message: "The actual hover card is missing")
                }
                let sizes: [CGFloat] = [13, 12, 11, 11]
                try UIVerification.require(presentation.fontSizes.count == sizes.count
                    && zip(presentation.fontSizes, sizes).allSatisfy { pair in abs(pair.0 - pair.1 * CGFloat(percent) / 100) < 0.1 }
                    && presentation.labelsFit, "The late hover card did not scale or its actual labels are clipped")
                try await GlassVerification.captureOwnedWindow(window,
                    to: output.appendingPathComponent("evidence/hover-\(percent).png"))
            }
            readability = true
        }
        browser.folderSummary.cancel()
        await ApplicationStorageAnalysis.shared.stopAndDrain()
        try UIVerification.require(!browser.folderSummary.isVisible && ApplicationFileActivity.gate.activeCount == 0,
            "Hover cancellation retained a card or I/O activity")
        return ["passed": true, "checks": ["actual table mouseMoved callback presents two-file summary", "repeated complete hover reuses exact access revision with zero new scanner starts",
            "return with Properties retained", "return with Settings and Properties retained", "disabled refuses delivery", "re-enable presents summary", "cancel drains actual worker"],
            "physical_pointer_qualified": false, "source_bodies_read": false,
            "scannerStarts": analysis.allScanStartsForSessionReuseVerification - starts,
            "readability100And150": readability, "gate_active": ApplicationFileActivity.gate.activeCount]
    }
}
#endif
