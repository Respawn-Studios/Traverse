import Foundation
import Testing
@testable import FileMemory
@testable import FileOperations

@Suite(.serialized) struct MoveMemberEvidenceTests {
    @Test(arguments: [false, true]) func b074cMergeFollowsPublishedMembersNotExistingContainers(nestedMerge: Bool) async throws {
        let f = try MoveFixture(), folder = f.source.appendingPathComponent("Project")
        let nested = folder.appendingPathComponent("Nested")
        try FileManager().createDirectory(at: nested, withIntermediateDirectories: true)
        let file = nested.appendingPathComponent("Document.txt")
        try Data("Generated merged descendant".utf8).write(to: file, options: .withoutOverwriting)
        let target = f.destination.appendingPathComponent("Project")
        try FileManager().createDirectory(at: target, withIntermediateDirectories: false)
        if nestedMerge { try FileManager().createDirectory(at: target.appendingPathComponent("Nested"), withIntermediateDirectories: false) }
        let engine = RecoverableFileOperations(journalDirectory: f.history)
        let plan = try await engine.prepareTransfer(sources: [folder], destinationDirectory: f.destination, move: true)
        let choices = Dictionary(uniqueKeysWithValues: plan.conflicts.map { ($0.id, TransferConflictResolution.merge) })
        let candidates = nestedMerge ? [file, folder, nested] : [file, folder]
        let admission = try await engine.observingMoveReferences(plan, candidates: candidates, resolutions: choices)
        #expect(admission.tickets.count == 1 && admission.omitted == candidates.count - 1)
        let ticket = try #require(admission.tickets.first)
        #expect(ticket.isMember == !nestedMerge)
        let moved = await engine.perform(admission.plan, resolutions: choices)
        try #require(moved.result.disposition == .succeeded)
        let receipt = moved.referenceReceipts.first
        #expect(try await engine.inspectMoveReference(ticket, direction: .forward, receipt: receipt).location.path
            == target.appendingPathComponent("Nested/Document.txt").path)
        try #require((await engine.undo(recordID: ticket.operationID)).result.disposition == .succeeded)
        #expect(try await engine.inspectMoveReference(ticket, direction: .undo, receipt: receipt).location.path == file.path)
        try f.receipt(["mergeMapsOnlyPublishedItems": true, "nestedMerge": nestedMerge])
    }

    @Test(arguments: [false, true]) func b074cSameVolumeMemberReceiptAndReplacementRefusal(replace: Bool) async throws {
        let f = try MoveFixture(), folder = f.source.appendingPathComponent("Project")
        let nested = folder.appendingPathComponent("Nested")
        try FileManager().createDirectory(at: nested, withIntermediateDirectories: true)
        let file = nested.appendingPathComponent("Document.txt")
        try Data("Generated nested document".utf8).write(to: file, options: .withoutOverwriting)
        let engine = RecoverableFileOperations(journalDirectory: f.history)
        let plan = try await engine.prepareTransfer(sources: [folder], destinationDirectory: f.destination, move: true)
        let admitted = try await engine.observingMoveReferences(plan, candidates: [file])
        let ticket = try #require(admitted.tickets.first)
        #expect(ticket.isMember && admitted.omitted == 0)
        let result = await engine.perform(admitted.plan)
        try #require(result.result.disposition == .succeeded)
        let receipt = try #require(result.referenceReceipts.first)
        #expect(try MoveReferenceReceipt(encoded: receipt.encoded()) == receipt)
        await #expect(throws: (any Error).self) { _ = try await engine.inspectMoveReference(ticket, direction: .forward) }
        let proof = try await engine.inspectMoveReference(ticket, direction: .forward, receipt: receipt)
        #expect(proof.location.path == f.destination.appendingPathComponent("Project/Nested/Document.txt").path)
        if replace {
            // Preserve the actual original; use equal generated bytes at its name.
            try FileManager().moveItem(at: proof.location, to: f.root.appendingPathComponent("Retained original.txt"))
            try Data("Generated nested document".utf8).write(to: proof.location, options: .withoutOverwriting)
            await #expect(throws: (any Error).self) {
                _ = try await engine.inspectMoveReference(ticket, direction: .forward, receipt: receipt)
            }
        } else {
            try #require((await engine.undo(recordID: ticket.operationID)).result.disposition == .succeeded)
            #expect(try await engine.inspectMoveReference(ticket, direction: .undo, receipt: receipt).location.path == file.path)
        }
        try f.receipt(["sameVolumeSelectedMember": true, "replacementRefused": replace])
    }

    @Test func b074cMemberAdmissionRejectsLinksAndOutsideCandidates() async throws {
        let f = try MoveFixture(), folder = f.source.appendingPathComponent("Project")
        try FileManager().createDirectory(at: folder, withIntermediateDirectories: false)
        let outside = try f.file(), link = folder.appendingPathComponent("Alias")
        try FileManager().createSymbolicLink(at: link, withDestinationURL: outside)
        let engine = RecoverableFileOperations(journalDirectory: f.history)
        let plan = try await engine.prepareTransfer(sources: [folder], destinationDirectory: f.destination, move: true)
        let admitted = try await engine.observingMoveReferences(plan, candidates: [link, outside, link])
        #expect(admitted.tickets.isEmpty && admitted.omitted == 3)
        #expect((await engine.perform(admitted.plan)).result.disposition == .succeeded)
        try f.receipt(["noLinkOrOutsideMembership": true])
    }
}
