    private static func attribute(_ name: String, on url: URL) throws -> Data? {
        let count = getxattr(url.path, name, nil, 0, 0, 0)
        if count < 0, errno == ENOATTR { return nil }
        guard count > 0 else { throw FileOperationFailure.ioFailure }
        var bytes = Data(count: count)
