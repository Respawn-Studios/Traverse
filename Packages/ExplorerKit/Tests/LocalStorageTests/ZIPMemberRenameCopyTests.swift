    private struct Header {
        let fixed: Data
        let localFixed: Data
        let name: Data
        let centralExtra: Data
        let centralComment: Data
        let localExtra: Data
    }
    private static func headers(_ bytes: Data) throws -> [Header] {
        let end = bytes.count - 22
        let count = Int(ZIPMetadataParser.u16(bytes, end + 10))
        var cursor = Int(ZIPMetadataParser.u32(bytes, end + 16))
        var entries: [Header] = []
        for _ in 0..<count {
            let fixed = Data(bytes[cursor..<(cursor + 46)])
            let names = Int(ZIPMetadataParser.u16(fixed, 28))
            let extras = Int(ZIPMetadataParser.u16(fixed, 30))
            let comments = Int(ZIPMetadataParser.u16(fixed, 32))
            let name = Data(bytes[(cursor + 46)..<(cursor + 46 + names)])
            let centralExtra = Data(bytes[(cursor + 46 + names)..<(cursor + 46 + names + extras)])
            let start = cursor + 46 + names + extras
            let centralComment = Data(bytes[start..<(start + comments)])
            let local = Int(ZIPMetadataParser.u32(fixed, 42))
            let localNames = Int(ZIPMetadataParser.u16(bytes, local + 26))
            let localExtras = Int(ZIPMetadataParser.u16(bytes, local + 28))
            let localExtra = Data(bytes[(local + 30 + localNames)..<(local + 30 + localNames + localExtras)])
            entries.append(.init(fixed: fixed, localFixed: Data(bytes[local..<(local + 30)]),
                name: name, centralExtra: centralExtra, centralComment: centralComment, localExtra: localExtra))
            cursor += 46 + names + extras + comments
        }
        XCTAssertEqual(cursor, end)
        return entries
    }
    private static func records(_ bytes: Data) throws -> [ZIPPayloadRecord] {
        var records: [ZIPPayloadRecord] = []
        _ = try ZIPMetadataParser.parse(length: UInt64(bytes.count), capture: { records.append($0) },
            cancelled: { false }, read: { offset, count in
                Data(bytes[Int(offset)..<(Int(offset) + count)])
            })
        return records
    }
    private static func localBytes(_ bytes: Data, named name: String) throws -> Data {
        let records = try records(bytes)
        let layout = try ZIPContentVerifier.prepare(records, limits: .init(), check: {},
            read: { offset, count in Data(bytes[Int(offset)..<(Int(offset) + count)]) })
        let extent = try XCTUnwrap(layout.extents.first { $0.record.name == name })
        return Data(bytes[Int(extent.record.localOffset)..<Int(extent.end)])
    }
    private static func packedAndDescriptor(_ bytes: Data, named name: String) throws -> Data {
        let records = try records(bytes)
        let layout = try ZIPContentVerifier.prepare(records, limits: .init(), check: {},
            read: { offset, count in Data(bytes[Int(offset)..<(Int(offset) + count)]) })
        let extent = try XCTUnwrap(layout.extents.first { $0.record.name == name })
        return Data(bytes[Int(extent.payload)..<Int(extent.end)])
    }
    private static func decoded(_ bytes: Data, named name: String) throws -> Data {
        let records = try records(bytes)
        let read: (UInt64, Int) throws -> Data = { offset, count in Data(bytes[Int(offset)..<(Int(offset) + count)]) }
        let layout = try ZIPContentVerifier.prepare(records, limits: .init(), check: {}, read: read)
        let extent = try XCTUnwrap(layout.extents.first { $0.record.name == name })
        var output = Data()
        try ZIPContentDecoder.check(method: extent.record.method, packed: extent.record.packed,
            logical: extent.record.logical, expectedCRC: extent.record.crc, check: {},
            read: { try read(extent.payload + $0, $1) }, decoded: { _ in }, consume: { output.append(contentsOf: $0) })
        return output
    }

    private static func nativeDocumentID(_ url: URL) throws -> UInt32 {
        let fd = open(url.path, O_RDONLY | O_NOFOLLOW_ANY | O_NONBLOCK | O_CLOEXEC)
        guard fd >= 0 else { throw FileOperationFailure.ioFailure }
        defer { close(fd) }
        var attributes = attrlist()
        attributes.bitmapcount = UInt16(ATTR_BIT_MAP_COUNT)
        attributes.commonattr = ATTR_CMN_RETURNED_ATTRS | UInt32(ATTR_CMN_DOCUMENT_ID)
        var bytes = [UInt8](repeating: 0, count: 64)
        guard fgetattrlist(fd, &attributes, &bytes, bytes.count, UInt32(FSOPT_ATTR_CMN_EXTENDED)) == 0 else {
            throw FileOperationFailure.ioFailure
        }
        func word(_ offset: Int) -> UInt32 {
            bytes.withUnsafeBytes { $0.loadUnaligned(fromByteOffset: offset, as: UInt32.self) }
        }
        guard word(0) == 28, word(4) & UInt32(ATTR_CMN_DOCUMENT_ID) != 0, word(24) != 0 else {
            throw FileOperationFailure.unsupported
        }
        return word(24)
    }

