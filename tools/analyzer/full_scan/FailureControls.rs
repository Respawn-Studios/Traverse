// Compiled into a separate test executable only, never the read-only worker.
#[cfg(test)]
mod native_dfs_failures {
    use super::*;
    use std::os::unix::fs::symlink;
    #[test] fn retained_frame_and_root_namespace_replacement_are_detected() {
        let text = std::env::var("B06_DFS_GENERATED_ROOT").expect("explicit generated root required");
        let base = std::env::current_dir().unwrap().join(".build/b06-analyzer");
        let path = std::path::PathBuf::from(&text);
        assert_eq!(path.parent(), Some(base.as_path()));
        let name = path.file_name().unwrap().to_str().unwrap();
        let suffix = name.strip_prefix("dfs-failure-").unwrap();
        assert!(suffix.len() == 32 && suffix.bytes().all(|c| c.is_ascii_hexdigit()));
        let generated = std::fs::symlink_metadata(path.join("nested/known")).unwrap();
        assert!(generated.file_type().is_file() && generated.len() == 21);
        let spelling = CString::new(text.clone()).unwrap();
        let root = Descriptor(unsafe { b06_open_root(spelling.as_ptr()) }); assert!(root.0 >= 0);
        let mut facts = Identity::default(); assert_eq!(unsafe { b06_identity(root.0, &mut facts) }, 0);
        let mut s = Scanner::new(Options { root_fd: -1, session: "00000000-0000-0000-0000-000000000000".into(),
            dev: facts.dev, ino: facts.ino, maximum_depth: 64, maximum_queue: 4096 });
        s.root_identity = facts; s.root_namespace = text.as_bytes().to_vec();
        let child_path = CString::new("nested").unwrap();
        let fd = Descriptor(unsafe { b06_open_directory(root.0, child_path.as_ptr()) }); assert!(fd.0 >= 0);
        let child = s.identity(fd.0).unwrap(); drop(fd);
        let pending = Pending { path: b"nested".to_vec(), dev: child.dev, ino: child.ino, depth: 1 };
        let frame = s.dfs_frame(root.0, pending.clone()).unwrap();
        std::fs::rename(path.join("nested"), path.join("retained-nested")).unwrap();
        symlink("retained-nested", path.join("nested")).unwrap();
        assert!(s.open_pending(root.0, &pending).is_err());
        let before = s.errors;
        s.dfs_close(root.0, &spelling, frame).unwrap();
        assert!(s.errors > before, "renamed retained directory did not report change");
        assert!(s.check_namespace(&spelling).is_ok());
        let moved = path.with_file_name(format!("{name}-retained"));
        std::fs::rename(&path, &moved).unwrap();
        symlink(moved.file_name().unwrap(), &path).unwrap();
        assert_eq!(s.check_namespace(&spelling), Err("root_replaced"));
        let held = s.identity(root.0).unwrap();
        assert_eq!((held.dev, held.ino), (facts.dev, facts.ino));
        // All original generated bytes and both substitution links remain as
        // evidence. No restore/delete or personal filesystem action occurs.
    }
}
