//! Generated memory-only remote filesystem, inside an actual encrypted SSH
//! session. This is not an interoperability or remote-power-loss test.
use super::{Counts,head,status,text,word};
use macexplorer_sftp_reader_qualification::{upload::MAX_CHUNK,wire};
use russh::{server,ChannelStream};
use std::sync::{Arc,atomic::Ordering};
use tokio::io::{AsyncReadExt,AsyncWriteExt};

#[derive(Default)]
pub struct Observed{
    pub temporary:Option<Vec<u8>>,pub final_file:Option<Vec<u8>>,
    pub operations:Vec<u8>,pub shutdown_seen:bool,
}
fn integer(bytes:&[u8],at:&mut usize)->u32{
    let value=u32::from_be_bytes(bytes[*at..*at+4].try_into().unwrap());*at+=4;value
}
fn wide(bytes:&[u8],at:&mut usize)->u64{
    let value=u64::from_be_bytes(bytes[*at..*at+8].try_into().unwrap());*at+=8;value
}
fn string<'a>(bytes:&'a[u8],at:&mut usize,limit:usize)->&'a[u8]{
    let length=integer(bytes,at)as usize;assert!(length<=limit);
    let value=&bytes[*at..*at+length];*at+=length;value
}
fn attrs(id:u32,size:usize,mode:u32)->Vec<u8>{
    let mut bytes=head(105,id);word(&mut bytes,5);bytes.extend((size as u64).to_be_bytes());word(&mut bytes,mode);bytes
}
pub async fn serve(stream:ChannelStream<server::Msg>,scenario:String,counts:Arc<Counts>){
    let observed=work(stream,&scenario,&counts).await;
    *counts.upload.lock().unwrap()=observed;
}
async fn work(mut stream:ChannelStream<server::Msg>,scenario:&str,counts:&Counts)->Observed{
    let final_path="/generated/Draft-Notes.bin";let mut temporary_path=Vec::new();
    let mut observed=Observed::default();let mut mode=0o100600;let mut final_checks=0;let mut final_handle=false;let mut exclusive=false;
    if scenario=="upload-conflict"{observed.final_file=Some(b"Keep existing generated bytes".to_vec())}
    loop{
        let length=match stream.read_u32().await{Ok(value)=>value as usize,Err(_)=>{observed.shutdown_seen=true;return observed}};
        assert!((5..=wire::MAX_PACKET).contains(&length));let mut bytes=vec![0;length];stream.read_exact(&mut bytes).await.unwrap();
        let kind=bytes[0];observed.operations.push(kind);counts.requests.fetch_add(1,Ordering::SeqCst);
        assert!(![13,14,15,20].contains(&kind));let id=if kind==1{0}else{u32::from_be_bytes(bytes[1..5].try_into().unwrap())};let mut at=5;
        let reply=match kind{
            1=>{assert_eq!(bytes,[1,0,0,0,3]);let mut reply=vec![2,0,0,0,3];text(&mut reply,b"fsync@openssh.com");text(&mut reply,b"1");reply},
            7=>{
                let path=string(&bytes,&mut at,8192);assert_eq!(at,bytes.len());
                if path==final_path.as_bytes(){
                    final_checks+=1;
                    if scenario=="upload-name-race"&&final_checks==2{observed.final_file=Some(b"Keep raced generated bytes".to_vec())}
                    observed.final_file.as_ref().map_or_else(||status(id,2),|v|attrs(id,v.len(),0o100644))
                }else{assert_eq!(path,temporary_path);attrs(id,observed.temporary.as_ref().unwrap().len(),mode)}
            },
            3=>{
                let path=string(&bytes,&mut at,8192);let flags=integer(&bytes,&mut at);let attributes=integer(&bytes,&mut at);
                if path==final_path.as_bytes()&&flags==0x2b{
                    exclusive=true;assert_eq!(attributes,4);assert_eq!(integer(&bytes,&mut at),0o600);assert_eq!(at,bytes.len());
                    if scenario=="upload-name-race"{observed.final_file=Some(b"Keep raced generated bytes".to_vec())}
                    if observed.final_file.is_some(){let reply=status(id,4);if stream.write_u32(reply.len()as u32).await.is_err()||stream.write_all(&reply).await.is_err(){return observed}continue}
                    observed.final_file=Some(Vec::new());
                    if scenario=="upload-lost-create"{return observed}
                    let mut reply=head(102,id);text(&mut reply,b"private\0\xff");
                    if stream.write_u32(reply.len()as u32).await.is_err()||stream.write_all(&reply).await.is_err(){return observed}continue
                }
                let handle=if path!=final_path.as_bytes(){
                    let prefix=b"/generated/.mac-explorer-upload-";let suffix=b".part";
                    assert!(path.starts_with(prefix)&&path.ends_with(suffix)&&path.len()==prefix.len()+32+suffix.len());
                    assert!(path[prefix.len()..prefix.len()+32].iter().all(|c|c.is_ascii_digit()||(b'A'..=b'F').contains(c)));temporary_path=path.to_vec();
                    assert_eq!((flags,attributes),(0x2b,4));assert_eq!(integer(&bytes,&mut at),0o600);assert!(observed.temporary.is_none());
                    observed.temporary=Some(Vec::new());if scenario=="upload-lost-create"{return observed}b"private\0\xff".as_slice()
                }else{
                    assert_eq!(path,final_path.as_bytes());assert_eq!((flags,attributes),(1,0));assert!(observed.final_file.is_some());final_handle=true;b"final\0".as_slice()
                };
                assert_eq!(at,bytes.len());let mut reply=head(102,id);text(&mut reply,handle);reply
            },
            6=>{
                assert_eq!(string(&bytes,&mut at,256),b"private\0\xff");let offset=wide(&bytes,&mut at)as usize;let data=string(&bytes,&mut at,MAX_CHUNK);assert_eq!(at,bytes.len());
                if scenario=="upload-stop-write"{
                    counts.upload_waiting.store(1,Ordering::Release);let mut end=[0];let _=stream.read(&mut end).await;observed.shutdown_seen=true;return observed
                }
                let file=if exclusive{observed.final_file.as_mut().unwrap()}else{observed.temporary.as_mut().unwrap()};assert_eq!(offset,file.len());file.extend(data);status(id,0)
            },
            8=>{
                let handle=string(&bytes,&mut at,256);assert_eq!(at,bytes.len());
                if handle==b"private\0\xff"{attrs(id,if exclusive{observed.final_file.as_ref().unwrap().len()}else{observed.temporary.as_ref().unwrap().len()},mode)}
                else{assert_eq!(handle,b"final\0");attrs(id,observed.final_file.as_ref().unwrap().len(),0o100644)}
            },
            5=>{
                counts.file_reads.fetch_add(1,Ordering::SeqCst);
                assert_eq!(string(&bytes,&mut at,256),if final_handle{b"final\0".as_slice()}else{b"private\0\xff".as_slice()});
                let offset=wide(&bytes,&mut at)as usize;let count=integer(&bytes,&mut at)as usize;assert_eq!(at,bytes.len());assert!((1..=MAX_CHUNK).contains(&count));
                if scenario=="upload-stop-readback"{
                    counts.upload_waiting.store(3,Ordering::Release);let mut end=[0];let _=stream.read(&mut end).await;observed.shutdown_seen=true;return observed
                }
                let file=if final_handle||exclusive{observed.final_file.as_ref().unwrap()}else{observed.temporary.as_ref().unwrap()};
                if offset>=file.len(){status(id,1)}else{let mut reply=head(103,id);text(&mut reply,&file[offset..(offset+count).min(file.len())]);reply}
            },
            10=>{
                assert_eq!(string(&bytes,&mut at,256),b"private\0\xff");assert_eq!(integer(&bytes,&mut at),4);mode=0o100000|integer(&bytes,&mut at);assert_eq!(mode,0o100644);assert_eq!(at,bytes.len());status(id,0)
            },
            200=>{
                assert_eq!(string(&bytes,&mut at,8192),b"fsync@openssh.com");assert_eq!(string(&bytes,&mut at,256),b"private\0\xff");assert_eq!(at,bytes.len());status(id,if scenario=="upload-sync-failure"{4}else{0})
            },
            4=>{
                assert_eq!(string(&bytes,&mut at,256),if final_handle{b"final\0".as_slice()}else{b"private\0\xff".as_slice()});assert_eq!(at,bytes.len());counts.closes.fetch_add(1,Ordering::SeqCst);
                if exclusive{counts.upload_published.store(observed.final_file.as_ref().unwrap().len()+1,Ordering::Release)}
                if scenario=="upload-lost-close"{return observed}status(id,0)
            },
            18=>{
                assert!(!exclusive,"G must never send RENAME");
                assert_eq!(string(&bytes,&mut at,8192),temporary_path);assert_eq!(string(&bytes,&mut at,8192),final_path.as_bytes());assert_eq!(at,bytes.len());assert!(observed.final_file.is_none());
                observed.final_file=observed.temporary.take();
                counts.upload_published.store(observed.final_file.as_ref().unwrap().len()+1,Ordering::Release);
                if scenario=="upload-lost-rename"{return observed}
                if scenario=="upload-stop-rename"{
                    counts.upload_waiting.store(2,Ordering::Release);let mut end=[0];let _=stream.read(&mut end).await;observed.shutdown_seen=true;return observed
                }status(id,0)
            },
            _=>panic!("Unexpected generated upload request"),
        };
        if stream.write_u32(reply.len()as u32).await.is_err()||stream.write_all(&reply).await.is_err(){return observed}
    }
}
