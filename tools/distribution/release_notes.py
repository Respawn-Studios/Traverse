#!/usr/bin/env python3
"""Validate the release history and produce the exact offline Swift catalog."""
import argparse
import datetime
import json
from pathlib import Path
import re
import sys

REPO = Path(__file__).resolve().parents[2]
CATALOG = REPO/'Distribution/ReleaseHistory.json'
GENERATED = REPO/'App/MacExplorer/ReleaseNotes.generated.swift'

def text(value, maximum):
    if not isinstance(value, str) or not 1 <= len(value.encode()) <= maximum \
        or any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ValueError('release text bound')
    return value

def read(path=CATALOG):
    data = path.read_bytes()
    return decode(data)

def decode(data):
    if len(data) > 256 << 10: raise ValueError('release history bound')
    root = json.loads(data)
    if set(root) != {'schema','releases'} or root['schema'] != 1 \
        or not isinstance(root['releases'], list) or not 1 <= len(root['releases']) <= 128:
        raise ValueError('release schema')
    previous_build = 1 << 63; previous_date = datetime.date.max
    for entry in root['releases']:
        if set(entry) != {'version','build','state','date','title','summary','changes'}:
            raise ValueError('release fields')
        version = text(entry['version'],32)
        if not re.fullmatch(r'(?:0|[1-9][0-9]{0,5})(?:\.(?:0|[1-9][0-9]{0,5})){2}',version):
            raise ValueError('release version')
        if type(entry['build']) is not int or not 0 < entry['build'] < previous_build:
            raise ValueError('release build order or duplicate')
        previous_build = entry['build']
        if entry['state'] not in ('published','preview','unreleased'): raise ValueError('release state')
        date = datetime.date.fromisoformat(entry['date'])
        if date.isoformat() != entry['date'] or date > previous_date: raise ValueError('release date order')
        previous_date = date
        text(entry['title'],160); text(entry['summary'],600)
        if not isinstance(entry['changes'],list) or not 1 <= len(entry['changes']) <= 24:
            raise ValueError('release changes')
        for change in entry['changes']:text(change,1000)
    return root

def release_for_build(root, version, build):
    """A display version can recur; the machine build selects its exact notes."""
    if type(build) is int:
        build = str(build)
    if not isinstance(build, str) or not re.fullmatch(r'[1-9][0-9]*', build):
        raise ValueError('release build identity')
    return next((entry for entry in root['releases']
                 if entry['version'] == version and str(entry['build']) == build), None)

def verify_bundled():
    if not GENERATED.is_file() or GENERATED.read_text()!=swift(read()):
        raise ValueError('bundled release notes differ from canonical history')

def swift(root):
    quote = lambda value: json.dumps(value,ensure_ascii=False)
    rows = []
    for entry in root['releases']:
        changes = ',\n                '.join(quote(v) for v in entry['changes'])
        rows.append(f'''        .init(version: {quote(entry['version'])}, build: {entry['build']}, state: .{entry['state']},
              date: {quote(entry['date'])}, title: {quote(entry['title'])},
              summary: {quote(entry['summary'])}, changes: [
                {changes}
              ])''')
    return '''// Generated by tools/distribution/release_notes.py from Distribution/ReleaseHistory.json.
// Edit the canonical catalog, then regenerate. Preview is never labelled released.
import Foundation

struct TraverseReleaseNote: Identifiable, Sendable {
    enum State: String, Sendable { case published, preview, unreleased }
    let version: String
    let build: Int
    let state: State
    let date: String
    let title: String
    let summary: String
    let changes: [String]
    var id: Int { build }
}

enum TraverseReleaseNotes {
    static let all: [TraverseReleaseNote] = [
''' + ',\n'.join(rows) + '\n    ]\n}\n'

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    source=swift(read())
    if args.write:GENERATED.write_text(source)
    elif not GENERATED.is_file() or GENERATED.read_text()!=source:
        raise SystemExit('Bundled release notes differ from the canonical history; regenerate them.')
    print('Release history and bundled notes agree.')

if __name__=='__main__':main()
